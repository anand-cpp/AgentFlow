// Provider key storage and environment merging.
//
// AgentFlow talks to hosted providers that need a bearer key. Those keys are
// secrets, and the rules for handling them are the whole point of this module:
//
//   1. Keys are never written into a project config file or committed. They live
//      in a single `keys.env` under the platform state directory, which sits
//      outside any checkout.
//   2. process.env always wins over keys.env. A user who exports GROQ_API_KEY in
//      their shell expects the shell to win, and a stale file must never quietly
//      shadow a live variable.
//   3. The file is written 0600 on Unix. On Windows we cannot cheaply express
//      "owner-only" through node:fs, so the setup command warns instead of
//      pretending the file is protected.
//
// This module is deliberately free of any import from the gateway so both the
// setup command and the gateway server can share it without a cycle.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import process from "node:process";

/** File mode for the keys file: owner read/write only. */
export const KEYS_FILE_MODE = 0o600;

/**
 * Root of the platform state directory.
 *
 * Mirrors the convention used by sessions, the event log, and the server state
 * file, but WITHOUT the per-subsystem suffix, so `keys.env` sits at the top of
 * the AgentFlow state tree.
 */
export function defaultStateDir() {
  if (process.env.AGENTFLOW_STATE_DIR) return process.env.AGENTFLOW_STATE_DIR;
  if (process.platform === "win32") {
    const base = process.env.LOCALAPPDATA || path.join(os.homedir(), "AppData", "Local");
    return path.join(base, "agentflow");
  }
  const base = process.env.XDG_STATE_HOME || path.join(os.homedir(), ".local", "state");
  return path.join(base, "agentflow");
}

/**
 * Path to the keys file.
 *
 * AGENTFLOW_KEYS_FILE wins outright so a test (or a user keeping keys on a
 * separate volume) can point it anywhere; otherwise it is
 * `<state dir>/keys.env`.
 */
export function defaultKeysFile() {
  if (process.env.AGENTFLOW_KEYS_FILE) return process.env.AGENTFLOW_KEYS_FILE;
  return path.join(defaultStateDir(), "keys.env");
}

/**
 * Parse dotenv text into a plain object.
 *
 * Deliberately small and forgiving: a malformed line is skipped rather than
 * throwing, because the file is user-editable and a single stray line must not
 * make every command that reads it fail. Supports `KEY=value`, `export KEY=value`,
 * comments, blank lines, and single/double quoted values.
 *
 * @param {string} text
 * @returns {Record<string, string>}
 */
export function parseDotenv(text) {
  /** @type {Record<string, string>} */
  const out = {};
  for (const rawLine of String(text ?? "").split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const match = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!match) continue;
    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"') && value.length >= 2) ||
      (value.startsWith("'") && value.endsWith("'") && value.length >= 2)
    ) {
      value = value.slice(1, -1);
    }
    out[match[1]] = value;
  }
  return out;
}

/**
 * Read keys.env, returning {} when it is missing or unreadable.
 *
 * A read failure is not fatal: the gateway must still start, and the wizard
 * treats a missing file as "nothing configured yet" rather than an error.
 *
 * @param {string} [file]
 * @returns {Record<string, string>}
 */
export function readKeysFile(file = defaultKeysFile()) {
  try {
    if (!fs.existsSync(file)) return {};
    return parseDotenv(fs.readFileSync(file, "utf8"));
  } catch {
    return {};
  }
}

/** Serialise a key map to dotenv text (sorted, with a header comment). */
export function serializeKeys(keys) {
  const lines = ["# AgentFlow provider keys -- generated by `aflow setup`."];
  lines.push("# This file contains secrets. Do not commit it or share it.");
  for (const name of Object.keys(keys || {}).sort()) {
    const value = keys[name];
    if (typeof value !== "string" || !value) continue;
    lines.push(`${name}=${value}`);
  }
  return `${lines.join("\n")}\n`;
}

/**
 * Write the keys file, creating parent directories and tightening permissions.
 *
 * @param {string} file
 * @param {Record<string, string>} keys
 * @param {{ mode?: number }} [opts]
 */
export function writeKeysFile(file, keys, { mode = KEYS_FILE_MODE } = {}) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  // Pass mode at creation so the file is never briefly world-readable, then
  // chmod again to tighten an already-existing file (rare on POSIX).
  fs.writeFileSync(file, serializeKeys(keys), { mode });
  if (process.platform !== "win32") {
    try {
      fs.chmodSync(file, mode);
    } catch {
      /* best effort: a filesystem without POSIX modes cannot express this */
    }
  }
  return file;
}

/** Merge `updates` into the existing keys file and return the merged map. */
export function updateKeys(updates, file = defaultKeysFile()) {
  const merged = { ...readKeysFile(file), ...updates };
  writeKeysFile(file, merged);
  return merged;
}

/** Delete the keys file. Returns true when a file was present and removed. */
export function removeKeysFile(file = defaultKeysFile()) {
  try {
    if (!fs.existsSync(file)) return false;
    fs.rmSync(file, { force: true });
    return true;
  } catch {
    return false;
  }
}

/**
 * Strip undefined/empty entries so a blank environment variable does not shadow
 * a real value from the keys file.
 */
export function cleanEnv(env) {
  /** @type {Record<string, string | undefined>} */
  const out = {};
  for (const [name, value] of Object.entries(env || {})) {
    if (typeof value === "string") {
      if (value.trim()) out[name] = value;
    } else if (value !== undefined && value !== null) {
      out[name] = /** @type {any} */ (value);
    }
  }
  return out;
}

/**
 * Merge a keys file under an environment, with the environment winning.
 *
 * @param {Record<string, string>} fileKeys
 * @param {NodeJS.ProcessEnv | Record<string, unknown>} [env]
 */
export function mergeEnv(fileKeys, env = process.env) {
  return { ...(fileKeys || {}), ...cleanEnv(env) };
}

/** Read keys.env and merge it under an environment. */
export function loadEnv({ file = defaultKeysFile(), env = process.env } = {}) {
  return mergeEnv(readKeysFile(file), env);
}

// ---------------------------------------------------------------------------
// provider readiness (shared with the gateway's resolveTargetProvider)
// ---------------------------------------------------------------------------

/**
 * The first non-empty value among a provider's accepted env vars.
 *
 * For an "any of" provider (e.g. Gemini accepts GEMINI_API_KEY or GOOGLE_API_KEY)
 * this is the credential. For an "all of" provider (Cloudflare needs both a token
 * and an account id) this is still the bearer, and the remaining keys are checked
 * by missingEnvKeys.
 *
 * @param {{ envKeys?: string[] }} spec
 * @param {Record<string, unknown>} env
 * @returns {string | null}
 */
export function firstKey(spec, env) {
  for (const name of spec?.envKeys || []) {
    const value = env?.[name];
    if (typeof value === "string" && value.trim()) return value.trim();
  }
  return null;
}

/** Names among an `all of` provider's env keys that are absent from `env`. */
export function missingEnvKeys(spec, env) {
  return (spec?.envKeys || []).filter((name) => {
    const value = env?.[name];
    return !(typeof value === "string" && value.trim());
  });
}

/**
 * Is a provider usable with this environment?
 *
 * `multiKey` providers require every listed key (Cloudflare: token AND account);
 * every other hosted provider needs just one credential.
 *
 * @param {{ envKeys?: string[], multiKey?: boolean, local?: boolean }} spec
 * @param {Record<string, unknown>} env
 */
export function providerReady(spec, env) {
  if (spec?.local) return true;
  if (spec?.multiKey) return missingEnvKeys(spec, env).length === 0;
  return Boolean(firstKey(spec, env));
}

/**
 * Resolve a provider base URL, substituting `{ENV_VAR}` placeholders.
 *
 * The placeholder names the environment variable directly, so a template like
 * `.../accounts/{CLOUDFLARE_ACCOUNT_ID}/ai/v1` needs no separate mapping table.
 * A missing variable resolves to the empty string; providerReady has already
 * rejected that case before a URL is ever built on the request path.
 *
 * @param {string} template
 * @param {Record<string, unknown>} env
 */
export function providerBaseUrl(template, env) {
  return String(template).replace(/\{([A-Za-z0-9_]+)\}/g, (_full, name) => {
    const value = env?.[name];
    return typeof value === "string" ? value.trim() : "";
  });
}

/** Names of non-local providers that are fully configured in `env`. */
export function configuredProviderNames(env, providers) {
  const out = [];
  for (const [name, spec] of Object.entries(providers || {})) {
    if (spec.local) continue;
    if (providerReady(spec, env)) out.push(name);
  }
  return out;
}

