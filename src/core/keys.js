export const PROVIDER_TEST_TIMEOUT_MS = 5000;

/**
 * A lightweight liveness probe for one provider.
 *
 * Uses `GET {baseUrl}/models` because it is the cheapest endpoint the OpenAI-
 * compatible providers share and it proves both reachability and that the key is
 * accepted. Two outcomes are deliberately distinguished rather than collapsed:
 *
 *   * 401/403 is a *credential* problem -- the key is wrong or missing scopes.
 *   * 404/405 means the endpoint exists but does not offer a listing (some
 *     providers do not); the key is neither proven nor disproven, so we report
 *     "reachable" rather than crying failure.
 *
 * A non-2xx that is neither is reported as an HTTP error, and a thrown fetch is
 * reported as unreachable. Nothing here throws.
 *
 * @param {{ baseUrl: string, envKeys?: string[], multiKey?: boolean }} spec
 * @param {{ env?: Record<string, unknown>, fetchImpl?: typeof fetch, timeoutMs?: number }} [opts]
 * @returns {Promise<{ ok: boolean, status: number | null, modelCount?: number | null, reason: string }>}
 */
export async function testProvider(spec, { env = {}, fetchImpl = globalThis.fetch, timeoutMs = PROVIDER_TEST_TIMEOUT_MS } = {}) {
  const baseUrl = providerBaseUrl(spec.baseUrl, env).replace(/\/+$/, "");
  const key = firstKey(spec, env);
  const url = `${baseUrl}/models`;

  try {
    const res = await fetchImpl(url, {
      method: "GET",
      headers: key ? { Authorization: `Bearer ${key}` } : {},
      signal: AbortSignal.timeout(timeoutMs),
    });

    if (res.ok) {
      let modelCount = null;
      try {
        const body = /** @type {{ data?: unknown[] }} */ (await res.json());
        modelCount = Array.isArray(body?.data) ? body.data.length : null;
      } catch {
        /* a 2xx with an unreadable body still proves reachability */
      }
      return { ok: true, status: res.status, modelCount, reason: "connected" };
    }
    if (res.status === 401 || res.status === 403) {
      return { ok: false, status: res.status, reason: "key rejected" };
    }
    if (res.status === 404 || res.status === 405) {
      return { ok: true, status: res.status, modelCount: null, reason: "reachable (no model listing)" };
    }
    return { ok: false, status: res.status, reason: `HTTP ${res.status}` };
  } catch (err) {
    const message = err?.name === "TimeoutError" ? "timed out" : err?.message || String(err);
    return { ok: false, status: null, reason: message };
  }
}

