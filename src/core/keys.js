/**
 * Render export commands for the user's shell.
 *
 * This is the one place a key value is intentionally printed: the user asked for
 * the commands to put the keys in their own environment, and those commands must
 * carry the values. Quotes are escaped so a value cannot break out of its quotes.
 *
 * @param {Record<string, string>} keys
 * @param {{ shell?: "posix" | "powershell" }} [opts]
 * @returns {string[]}
 */
export function formatExport(keys, { shell = process.platform === "win32" ? "powershell" : "posix" } = {}) {
  const lines = [];
  for (const name of Object.keys(keys || {}).sort()) {
    const value = keys[name];
    if (typeof value !== "string" || !value) continue;
    if (shell === "powershell") {
      lines.push(`$env:${name} = "${value.replace(/"/g, '`"')}"`);
    } else {
      lines.push(`export ${name}='${value.replace(/'/g, "'\\''")}'`);
    }
  }
  return lines;
}

